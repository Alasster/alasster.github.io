  function markup(icon, className = '') {
    const name = available.has(icon) ? icon : 'book-alt';
    return `<i class="lesson-flaticon ${className}" data-flaticon="${name}" aria-hidden="true"></i>`;
  }

  function stage(lessonId, index) {
    return stages[lessonId]?.[index] || null;
  }

  function decorate(root) {
    if (!(root instanceof Element)) return;
    const legacyIcons = root.matches('i[class]') ? [root] : [...root.querySelectorAll('i[class]')];
    for (const icon of legacyIcons) {
      const name = [...icon.classList].find(value => aliases[value.replace(/^fa-/, '')] && value.startsWith('fa-'));
      if (!name) continue;
      const mapped = aliases[name.slice(3)];
      icon.dataset.flaticon = mapped;
      icon.classList.add('lesson-flaticon');
      if (!icon.hasAttribute('aria-label')) icon.setAttribute('aria-hidden', 'true');
    }
    // Replace decorative emoji only in dedicated icon containers; lesson text and data stay intact.
    const containers = root.matches('.bigicon, .big-icon, .icon, .screen, .flow-icon, .model-icon')
      ? [root] : [...root.querySelectorAll('.bigicon, .big-icon, .icon, .screen, .flow-icon, .model-icon')];
    for (const container of containers) {
      if (container.children.length) continue;
      const name = emoji[container.textContent.trim()];
      if (name) container.innerHTML = markup(name);
    }
  }

  function init() {
    decorate(document.body);

    const observer = new MutationObserver(records => {
      const roots = new Set();
      for (const record of records) {
        if (record.type === 'attributes') {
          if (record.target.matches('i[class]')) {
            const name = [...record.target.classList].find(value => value.startsWith('fa-') && aliases[value.slice(3)]);
            if (name && aliases[name.slice(3)] !== record.target.dataset.flaticon) roots.add(record.target);
          }
        } else {
          for (const node of record.addedNodes) if (node instanceof Element) roots.add(node);
        }
      }
      for (const root of roots) decorate(root);
    });
    observer.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['class'] });
  }

  window.AlassterLessonIcons = { markup, stage, stages, decorate };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
